unsigned int Font::createTexture() {
    const int W = COUNT * CELL_W, H = CELL_H;
    std::vector<unsigned char> pixels(W * H, 0);
    for (const Glyph& g : GLYPHS) {
        int cell = g.c - FIRST;
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++)
                if (g.rows[row][col] == '#') pixels[row * W + cell * CELL_W + col] = 255;
    }
    unsigned int tex;
    glGenTextures(1, &tex);
    glBindTexture(GL_TEXTURE_2D, tex);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, W, H, 0, GL_RED, GL_UNSIGNED_BYTE, pixels.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    return tex;
}
