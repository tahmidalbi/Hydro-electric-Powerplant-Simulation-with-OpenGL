const char* BitmapFont::glyphRow(char c, int row) {
    if (row < 0 || row >= GLYPH_H) return nullptr;
    c = (char)std::toupper((unsigned char)c);
    for (const Glyph& g : GLYPHS)
        if (g.c == c) return g.rows[row];
    return nullptr;
}
